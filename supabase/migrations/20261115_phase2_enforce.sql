-- Phase 2 enforcement. DO NOT APPLY until at least one public.members row has role='admin'.
-- Club treasurers: read/write assigned club
-- Auditors: read assigned club
-- Viewers: read assigned club
-- Admins: read/write all clubs

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create or replace function private.can_access_club(p_club_name text, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.members m
    left join public.clubs c on c.id = m.club_id
    where m.user_id = (select auth.uid())
      and (
        m.role = 'admin'
        or (
          c.name = p_club_name
          and (
            (p_write = false and m.role in ('treasurer','auditor','viewer'))
            or (p_write = true and m.role = 'treasurer')
          )
        )
      )
  );
$$;

revoke all on function private.can_access_club(text, boolean) from public, anon;
grant execute on function private.can_access_club(text, boolean) to authenticated;

drop policy if exists "Allow authenticated access" on public.transactions;
drop policy if exists uniten_students_only on public.transactions;

create policy treasury_transactions_select
on public.transactions for select
to authenticated
using ((select private.can_access_club(club_name, false)));

create policy treasury_transactions_insert
on public.transactions for insert
to authenticated
with check (
  (select private.can_access_club(club_name, true))
  and lower(user_email) = lower((select auth.jwt() ->> 'email'))
  and amount > 0
);

create policy treasury_transactions_update
on public.transactions for update
to authenticated
using ((select private.can_access_club(club_name, true)))
with check (
  (select private.can_access_club(club_name, true))
  and amount > 0
);

create policy treasury_transactions_delete
on public.transactions for delete
to authenticated
using ((select private.can_access_club(club_name, true)));

drop policy if exists "Members viewable by club affiliates or auditors" on public.members;
create policy treasury_members_self_read
on public.members for select
to authenticated
using (
  user_id = (select auth.uid())
  or exists (
    select 1 from public.members admin_member
    where admin_member.user_id = (select auth.uid())
      and admin_member.role = 'admin'
  )
);

-- Audit rows are generated by the trigger, not directly by clients.
drop policy if exists treasury_audit_admin_read on public.audit_log;
create policy treasury_audit_admin_read
on public.audit_log for select
to authenticated
using (
  exists (
    select 1 from public.members m
    where m.user_id = (select auth.uid()) and m.role = 'admin'
  )
);
